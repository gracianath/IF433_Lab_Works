package oop_116931_GraciaNathania.week05

class MathHelper() {
    fun hitungLuasPersegi(sisi: Int): Int{
        return sisi * sisi
    }

    fun hitungLuasPersegiPanjang(panjang: Int, lebar: Int): Int{
        return panjang * lebar
    }

    fun hitungLuasLingkaran(jariJari: Double): Double{
        return 3.14 * jariJari * jariJari
    }
}